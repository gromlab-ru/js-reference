// =============================================================================
// Вернуть промис или дождаться его в try
//
// При отказе меняется место обработки ошибки: внутри функции или у вызывающего кода.
// =============================================================================
{
  const read = async (): Promise<string> => { throw new Error('Нет записи') }

  // Вариант А
  async function direct() {
    try { return read() } catch { return 'Обработано внутри' }
  }

  // Вариант Б
  async function awaited() {
    try { return await read() } catch { return 'Обработано внутри' }
  }

  await direct().catch(() => 'Обработано снаружи') // 'Обработано снаружи'
  await awaited() // 'Обработано внутри'
}

// =============================================================================
// Последовательный или совместный запуск
//
// Посмотрите в журнале, начал ли второй шаг работу до завершения первого.
// =============================================================================
{
  const log: string[] = []
  const step = async (id: string) => {
    log.push(`начало ${id}`)
    await Promise.resolve()
    log.push(`конец ${id}`)
  }

  // Вариант А
  await step('A')
  await step('Б')
  log.slice() // ['начало A', 'конец A', 'начало Б', 'конец Б']

  // Вариант Б
  log.length = 0
  await Promise.all([step('A'), step('Б')])
  log.slice() // ['начало A', 'начало Б', 'конец A', 'конец Б']
}

// =============================================================================
// Promise.all и Promise.allSettled
//
// Один пакет принят, второй отклонён. Какие результаты доступны вызывающему коду?
// =============================================================================
{
  const send = async (id: number) => {
    if (id === 2) throw new Error('Пакет отклонён')
    return id
  }

  // Вариант А — общий промис отклонён; уже начатые операции не отменяются.
  await Promise.all([send(1), send(2)]).catch(() => 'Ошибка отправки')

  // Вариант Б — отдельный исход каждой операции, в порядке входных значений.
  const results = await Promise.allSettled([send(1), send(2)])
  results.map(result => result.status) // ['fulfilled', 'rejected']
}

// =============================================================================
// Асинхронный обход
//
// Когда сохранены все записи? forEach не возвращает промисы вызовов.
// =============================================================================
{
  const ids = ['o1', 'o2']
  const saved: string[] = []
  const save = async (id: string) => {
    await Promise.resolve()
    saved.push(id)
  }

  // Вариант А — по очереди.
  for (const id of ids) await save(id)
  saved.slice() // ['o1', 'o2']

  // Вариант Б — вместе, с ожиданием всех.
  saved.length = 0
  await Promise.all(ids.map(save))
  saved.slice() // ['o1', 'o2']

  // Вариант В — в этой точке записи ещё не сохранены.
  saved.length = 0
  ids.forEach(async id => { await save(id) })
  saved.slice() // []
}

// =============================================================================
// Кто обрабатывает отказ фоновой операции
//
// Если отправка не нужна для ответа, где всё-таки будет замечен её отказ?
// =============================================================================
{
  const send = async () => { throw new Error('Не доставлено') }
  const failures: unknown[] = []

  // Вариант А — вызывающий код дожидается результата.
  try { await send() } catch (error) { failures.push(error) }

  // Вариант Б — обработчик закреплён за самой фоновой операцией.
  void send().catch(error => { failures.push(error) })
}

// =============================================================================
// Отмена операции
//
// Родитель уже отменил загрузку. Дойдёт ли причина отмены до внутреннего шага?
// =============================================================================
{
  const load = async (signal: AbortSignal) => {
    signal.throwIfAborted()
    return 'Загружено'
  }
  const request = new AbortController()
  request.abort(new Error('Заявка закрыта'))

  // Вариант А — независимый сигнал не знает об отмене родителя.
  await load(new AbortController().signal) // 'Загружено'

  // Вариант Б — передан сигнал родителя.
  await load(request.signal).catch((reason: unknown) => reason === request.signal.reason) // true
}

