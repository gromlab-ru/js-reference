// =============================================================================
// Класс и конструктор
//
// Для класса важно назначение, для конструктора — сохранится ли связь с входным массивом.
// =============================================================================
{
  // Хорошо
  {
    /** Хранит план повторов на момент постановки заявки в очередь. */
    class RetrySchedule {
      readonly delays: readonly number[]
      /** Делает копию: последующие изменения исходного массива не меняют план. */
      constructor(delays: readonly number[]) { this.delays = [...delays] }
    }
  }

  // Плохо
  {
    /** Класс плана повторов. */
    class RetrySchedule {
      readonly delays: readonly number[]
      /** Создаёт экземпляр класса. */
      constructor(delays: readonly number[]) { this.delays = [...delays] }
    }
  }
}

// =============================================================================
// Поле, метод и геттер
//
// Указано ли, что расходует попытку, а что только читает счётчик?
// =============================================================================
{
  // Хорошо
  {
    class Attempts {
      /** Число уже начатых попыток, включая ещё не завершённые. */
      private count = 0
      /** Чтение не резервирует попытку. */
      get used() { return this.count }
      /** Резервирует попытку и возвращает её номер начиная с единицы. */
      take() { return ++this.count }
    }
  }

  // Плохо
  {
    class Attempts {
      /** Счётчик. */
      private count = 0
      /** Геттер счётчика. */
      get used() { return this.count }
      /** Увеличивает count. */
      take() { return ++this.count }
    }
  }
}

