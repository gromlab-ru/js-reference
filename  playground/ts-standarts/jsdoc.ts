// =============================================================================
// Назначение функции и побочный эффект
//
// По имени takeNext неясно, останется ли элемент в очереди после чтения.
// =============================================================================
{
  // Хорошо
  {
    /**
     * Удаляет первую заявку из очереди и возвращает её.
     *
     * `queue`: заявки, ожидающие отправки.
     */
    function takeNext(queue: string[]): string | undefined {
      return queue.shift()
    }
  }

  // Плохо
  {
    /**
     * Возвращает следующую заявку.
     *
     * `queue`: заявки, ожидающие отправки.
     */
    function takeNext(queue: string[]): string | undefined {
      return queue.shift()
    }
  }
}

// =============================================================================
// Параметры и результат
//
// В сигнатуре два числа. С какого номера начинается отсчёт и в чём измеряется результат?
// =============================================================================
{
  // Хорошо
  {
    /**
     * Вычисляет задержку перед повтором.
     *
     * `attempt`: номер повторной отправки.
     *  - `0` — первый повтор, через одну секунду
     *
     * @returns Задержка в миллисекундах.
     */
    function delay(attempt: number): number { return 1000 * 2 ** attempt }
  }

  // Плохо
  {
    /**
     * Вычисляет задержку перед повтором.
     *
     * `attempt`: число.
     *
     * @returns Число.
     */
    function delay(attempt: number): number { return 1000 * 2 ** attempt }
  }
}

// =============================================================================
// Условия ошибки
//
// Как вызывающему коду заранее определить, допустимо ли значение?
// =============================================================================
{
  // Хорошо
  {
    /** @throws {RangeError} Если задержка отрицательная или не является конечным числом. */
    function validateDelay(ms: number): number {
      if (!Number.isFinite(ms) || ms < 0) throw new RangeError('Недопустимая задержка')
      return ms
    }
  }

  // Плохо
  {
    /** @throws Может выбросить ошибку. */
    function validateDelay(ms: number): number {
      if (!Number.isFinite(ms) || ms < 0) throw new RangeError('Недопустимая задержка')
      return ms
    }
  }
}

