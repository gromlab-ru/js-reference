// =============================================================================
// Пример, ссылка и устаревший API
//
// Достаточно ли подсказки редактора, чтобы заменить старый вызов без ошибки на единицу?
// =============================================================================
/** Возвращает задержку до следующей попытки в миллисекундах. */
export function retryDelay(attempt: number): number {
  return 1000 * 2 ** attempt
}

{
  // Хорошо
  {
    /**
     * @deprecated Используй {@link retryDelay}: там отсчёт начинается с нуля.
     * @example
     * firstRetryDelay(1) // 1000 мс
     * retryDelay(0) // 1000 мс
     */
    function firstRetryDelay(attempt: number) { return retryDelay(attempt - 1) }
  }

  // Плохо
  {
    /** @deprecated Устарело. */
    function firstRetryDelay(attempt: number) { return retryDelay(attempt - 1) }
  }
}

