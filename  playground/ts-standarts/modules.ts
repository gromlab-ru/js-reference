// =============================================================================
// Порядок импортов и регистрация при загрузке
//
// Все статические импорты выполняются до тела модуля, даже записанные ниже.
// В каком варианте видно, в какой момент в справочнике появится подпись?
// =============================================================================
// Вариант А — модуль при загрузке заполняет общий справочник.
import './module-example/register-pickup.js'

labelFor('pickup') // 'Самовывоз', в том числе при вызове на первой строке тела модуля.

// Вариант Б — порядок действий виден в коде. Локальный справочник изначально пуст.
import { registerPickup } from './module-example/catalog.js'

{
  const local = new Map<DeliveryCode, string>()
  labelFor('pickup', local) // 'pickup'
  registerPickup(local)
  labelFor('pickup', local) // 'Самовывоз'
}

// =============================================================================
