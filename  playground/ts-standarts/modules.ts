// =============================================================================
// Порядок объявлений и видимость
//
// Две одинаковые по результату операции экспортированы. Внутренние функции
// остаются недоступны для импорта независимо от их места в файле.
// =============================================================================
// Вариант А — сначала публичная операция.
export function receiptTitle(id: string) { return `Чек №${cleanId(id)}` }
function cleanId(id: string) { return id.trim() }

// Вариант Б — сначала подробность реализации.
function trimId(id: string) { return id.trim() }
export function titleForReceipt(id: string) { return `Чек №${trimId(id)}` }
