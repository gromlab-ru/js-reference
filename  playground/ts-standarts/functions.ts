// =============================================================================
// Объявление функции
//
// Один расчёт в двух формах. Попробуйте переместить вызов перед объявлением:
// функция через function доступна раньше, переменная const — только после инициализации.
// =============================================================================
{
  // Вариант А
  {
    function lineTotal(price: number, count: number) { return price * count }
    lineTotal(40, 2)
  }

  // Вариант Б
  {
    const lineTotal = (price: number, count: number) => price * count
    lineTotal(40, 2)
  }
}

// =============================================================================
// Позиционные параметры и объект параметров
//
// Можно ли при вызове перепутать два числа одного типа?
// =============================================================================
{
  const ids = ['a', 'b', 'c', 'd']

  // Вариант А
  {
    const page = (offset: number, limit: number) => ids.slice(offset, offset + limit)
    page(2, 1) // ['c']; при перестановке чисел получится ['b', 'c'].
  }

  // Вариант Б
  {
    const page = ({ offset, limit }: { offset: number; limit: number }) => ids.slice(offset, offset + limit)
    page({ offset: 2, limit: 1 }) // ['c']
  }
}

// =============================================================================
// Деструктуризация параметра
//
// Сравниваем извлечение тех же полей в сигнатуре и в теле функции.
// =============================================================================
{
  type Label = { city: string; street: string }

  // Вариант А
  const fromParams = ({ city, street }: Label) => `${city}, ${street}`

  // Вариант Б
  const fromBody = (label: Label) => {
    const { city, street } = label
    return `${city}, ${street}`
  }
}

// =============================================================================
// Необязательный параметр и значение по умолчанию
//
// В обеих записях пропущенный лимит равен 20, а переданный 0 сохраняется.
// =============================================================================
{
  // Вариант А
  const optional = (limit?: number) => limit ?? 20

  // Вариант Б
  const withDefault = (limit = 20) => limit

  ;[optional(), withDefault(), optional(0), withDefault(0)] // [20, 20, 0, 0]
}

// =============================================================================
// Явный или выведенный тип результата
//
// Замените объект на строку: в каком варианте ошибка появится у return?
// =============================================================================
{
  type Receipt = { total: number }

  // Вариант А
  function explicit(total: number): Receipt { return { total } }

  // Вариант Б
  function inferred(total: number) { return { total } }
}

// =============================================================================
// Перегрузки, объединение и отдельные функции
//
// Нормализуем один код или список. Наведите курсор на результаты трёх вызовов.
// =============================================================================
{
  const trim = (code: string) => code.trim()
  const trimAll = (codes: string[]) => codes.map(trim)

  // Вариант А — сигнатуры сохраняют связь входа с результатом.
  function normalize(value: string): string
  function normalize(value: string[]): string[]
  function normalize(value: string | string[]): string | string[] {
    return typeof value === 'string' ? trim(value) : trimAll(value)
  }
  normalize(' A ') // string

  // Вариант Б — на выходе остаётся объединение.
  const normalizeEither = (value: string | string[]) =>
    typeof value === 'string' ? trim(value) : trimAll(value)
  normalizeEither(' A ') // string | string[]

  // Вариант В — форму входа выбирают на месте вызова.
  trim(' A ') // string
  trimAll([' A ']) // string[]
}

// =============================================================================
// Передача функции как обратного вызова
//
// map передаёт индекс вторым аргументом. У parseInt на этом месте основание счисления.
// =============================================================================
{
  const codes = ['10', '10', '10']

  // Хорошо — явно выбрана десятичная запись.
  codes.map(code => parseInt(code, 10)) // [10, 10, 10]

  // Плохо — индекс незаметно меняет смысл вызова.
  codes.map(parseInt) // [10, NaN, 2]
}

// =============================================================================
// Выделение вспомогательной функции
//
// Что удобнее читать в расчёте чека: формулу скидки или имя отдельного шага?
// =============================================================================
{
  const prices = [120, 80]

  // Вариант А
  prices.map(price => Math.round(price * 0.9))

  // Вариант Б
  const applyLoyaltyDiscount = (price: number) => Math.round(price * 0.9)
  prices.map(applyLoyaltyDiscount)
}
