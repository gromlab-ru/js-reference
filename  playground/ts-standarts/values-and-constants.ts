// =============================================================================
// const и let
//
// Меняется ли переменная или только массив, который в ней хранится?
// =============================================================================
{
  // Вариант А — тот же массив виден через прежнюю ссылку.
  {
    const ids = ['u1']
    const original = ids
    ids.push('u2')
    original.length // 2
  }

  // Вариант Б — переменная указывает на другой массив.
  {
    let ids = ['u1']
    const original = ids
    ids = [...ids, 'u2']
    original.length // 1
  }
}

// =============================================================================
// Инициализация сразу или в ветках
//
// Оба варианта выбирают одну плату за доставку.
// =============================================================================
{
  const shippingFee = (pickup: boolean) => {
    // Вариант А
    const fee = pickup ? 0 : 300

    // Вариант Б
    let amount: number
    if (pickup) amount = 0
    else amount = 300

    return [fee, amount]
  }
  shippingFee(true) // [0, 0]
}

// =============================================================================
// Литерал или именованная константа
//
// Понятно ли из сравнения, почему выбран именно этот предел?
// =============================================================================
{
  const canSend = (size: number) => {
    // Вариант А
    const fitsBatch = size <= 100

    // Вариант Б
    const maxBatchSize = 100
    const fitsRequest = size <= maxBatchSize

    return [fitsBatch, fitsRequest]
  }
  canSend(101) // [false, false]
}

// =============================================================================
// Представление набора значений
//
// Строки совпадают. Чем отличаются обращения к отдельным значениям?
// =============================================================================
{
  // Вариант А — отдельные константы.
  const PENDING = 'pending'
  const PAID = 'paid'

  // Вариант Б — объект.
  const PAYMENT = { PENDING: 'pending', PAID: 'paid' } as const

  // Вариант В — перечисление.
  enum Payment { Pending = 'pending', Paid = 'paid' }

  ;[PAID, PAYMENT.PAID, Payment.Paid] // Три строки 'paid'.
}

// =============================================================================
// Тип из значений или отдельное объявление
//
// Добавьте статус в объект и посмотрите, какой тип обновится без второй правки.
// =============================================================================
{
  const STATUS = { PENDING: 'pending', PAID: 'paid' } as const

  // Вариант А
  type FromValues = (typeof STATUS)[keyof typeof STATUS]

  // Вариант Б
  type WrittenOut = 'pending' | 'paid'

  STATUS.PAID satisfies FromValues
  STATUS.PAID satisfies WrittenOut
}
