// =============================================================================
// Объединения и пересечения
//
// Сравниваем положение | и & в начале и в конце строки.
// =============================================================================
{
  // Вариант А
  {
    type Status =
      | 'awaiting_confirmation'
      | 'awaiting_delivery'
    type Shipment =
      & { trackingNumber: string }
      & { status: Status }
  }

  // Вариант Б
  {
    type Status = 'awaiting_confirmation' |
      'awaiting_delivery'
    type Shipment = { trackingNumber: string } &
      { status: Status }
  }
}

// =============================================================================
// Цепочка вызовов и длинное условие
//
// Сравниваем переносы между операциями на одних и тех же данных.
// =============================================================================
{
  const orders = [{ id: 'o1', paid: true, shipped: false, cancelled: false }]

  // Вариант А
  orders
    .filter(order =>
      order.paid &&
      !order.shipped &&
      !order.cancelled
    )
    .map(order => order.id)
    .join(', ')

  // Вариант Б
  orders.filter(order => order.paid && !order.shipped && !order.cancelled)
    .map(order => order.id).join(', ')
}
