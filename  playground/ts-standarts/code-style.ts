// =============================================================================
// Пробелы и отступы
//
// Две записи одного вычисления. Сравниваем отступ в блоке и пробелы у операторов.
// =============================================================================
{
  const prices = [80, 120]

  // Хорошо
  prices.map((price: number) => {
    return price * 2
  })

  // Плохо
  prices.map((price :number)=>{
      return price*2
  })
}

// =============================================================================
// Пустая строка между шагами
//
// Где удобнее увидеть переход от подготовки чисел к расчёту суммы?
// =============================================================================
{
  const prices = [80, 120]

  // Вариант А
  {
    const amounts = prices.map(price => price * 100)

    amounts.reduce((sum, amount) => sum + amount, 0)
  }

  // Вариант Б
  {
    const amounts = prices.map(price => price * 100)
    amounts.reduce((sum, amount) => sum + amount, 0)
  }
}

