// =============================================================================
// Точка с запятой и завершающая запятая
//
// Обмениваем значения. Разделитель перед [ нужен, если предыдущая строка открыта
// для продолжения; запятая после последнего элемента пары необязательна.
// =============================================================================
{
  // Хорошо
  {
    let first = 1
    let second = 2
    ;[first, second] = [second, first]
  }

  // Плохо
  {
    let first = 1;
    let second = 2;
    [first, second] = [second, first,];
  }
}

