// =============================================================================
// Объект, Record, Partial и Map
//
// Когда все ключи известны, а когда при чтении нужно обработать отсутствие записи?
// =============================================================================
{
  type Zone = 'city' | 'region'

  // Вариант А — ключи определяются именами свойств объекта.
  const rates = { city: 100, region: 200 }

  // Вариант Б — отсутствие любого из двух ключей станет ошибкой типов.
  const complete: Record<Zone, number> = { city: 100, region: 200 }

  // Вариант В — тариф для региона ещё не задан.
  const draft: Partial<Record<Zone, number>> = { city: 100 }
  const byZone = new Map<Zone, number>([['city', 100]])
  ;[draft.region, byZone.get('region')] // [undefined, undefined]
}

// =============================================================================
// Найти значение или проверить наличие
//
// Что нужно потребителю: сама запись, наличие записи или поиск ключа в индексе?
// =============================================================================
{
  const orders = [{ id: 'o1', paid: false }, { id: 'o2', paid: true }]

  // Вариант А — запись или undefined.
  const paid = orders.find(order => order.paid)

  // Вариант Б — только ответ да/нет.
  const hasPaid = orders.some(order => order.paid)

  // Вариант В — проверка конкретного идентификатора.
  const ids = orders.map(order => order.id)
  ids.includes('o2')
  const uniqueIds = new Set(ids)
  uniqueIds.has('o2')
}

// =============================================================================
// map и filter, reduce или цикл
//
// Во всех трёх записях остаются только положительные суммы, переведённые в копейки.
// =============================================================================
{
  const amounts = [0, 12, -4, 5]

  // Вариант А
  amounts.filter(amount => amount > 0).map(amount => amount * 100)

  // Вариант Б
  amounts.reduce<number[]>((result, amount) => {
    if (amount > 0) result.push(amount * 100)
    return result
  }, [])

  // Вариант В
  const kopecks: number[] = []
  for (const amount of amounts) {
    if (amount > 0) kopecks.push(amount * 100)
  }
}

// =============================================================================
// Пустая коллекция и отсутствие коллекции
//
// Список ещё не загружен или уже загружен и пуст? Нужен ли читателю этот ответ?
// =============================================================================
{
  // Вариант А — счётчик не различает эти состояния.
  const count = (ids?: readonly string[]) => (ids ?? []).length
  ;[count(), count([])] // [0, 0]

  // Вариант Б — подпись должна различать оба состояния.
  const label = (ids?: readonly string[]) => ids === undefined ? 'Загрузка' : `Найдено: ${ids.length}`
  ;[label(), label([])] // ['Загрузка', 'Найдено: 0']
}
