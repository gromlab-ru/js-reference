/** Часы диспетчера для отложенной отправки. */
export interface DispatchClock {
      /**
  * Планирует повторную отправку заявки, если перевозчик не успел подтвердить её получение до истечения времени ожидания.
*  - `0` — начать сразу
         *  - положительное значение — подождать
      *
    * @param    delayMs     Задержка перед повтором в миллисекундах.
         */
    retry(delayMs: number): void
}

/** Задержка между повторными отправками в миллисекундах. **/
export type RetryDelay = number
